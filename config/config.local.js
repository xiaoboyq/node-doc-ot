'use strict';
const path = require('path');
/**
 * @param {Egg.EggAppInfo} appInfo app info
 */
module.exports = appInfo => {
  /**
   * built-in config
   * @type {Egg.EggAppConfig}
   **/
  const config = exports = {};

  config.logger = {
    dir: path.join(appInfo.baseDir, 'logs'),
  };


  return {
    ...config,
  };
};
